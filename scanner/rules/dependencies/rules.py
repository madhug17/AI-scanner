class DependencyVulnerabilitiesRule(SecurityRule):
    """SEC-032: Identifies known vulnerable dependencies in requirement files."""
    rule_id = "SEC-032"
    title = "Known Vulnerable Dependency"
    category = "Dependencies"
    severity = Severity.HIGH
    default_status = FindingStatus.CONFIRMED
    description = "A pinned dependency version has a known public vulnerability (CVE/GHSA)."
    impact = "Known security defects in external libraries can be exploited directly against the application."
    recommendation = "Upgrade the vulnerable library to the latest patched version."

    DEP_LINE_PATTERN = re.compile(r"^([a-zA-Z0-9_\-\.]+)\s*==\s*([0-9a-zA-Z\.\-]+)")

    def scan(self, file_path: str, content: str) -> list[Finding]:
        findings = []
        norm_path = file_path.replace("\\", "/").lower()
        if not (norm_path.endswith("requirements.txt") or "requirements" in norm_path or norm_path.endswith("pipfile")):
            return findings

        for line_no, line in enumerate(content.splitlines(), start=1):
            clean_line = line.strip()
            if clean_line.startswith("#") or not clean_line:
                continue

            match = self.DEP_LINE_PATTERN.match(clean_line)
            if match:
                pkg = match.group(1).lower()
                version = match.group(2)
                if pkg in KNOWN_VULNERABLE_PACKAGES:
                    vuln_info = KNOWN_VULNERABLE_PACKAGES[pkg]
                    if version in vuln_info:
                        cve = vuln_info[version]
                        findings.append(
                            self.create_finding(
                                file_path=file_path,
                                line_start=line_no,
                                line_end=line_no,
                                code_snippet=clean_line,
                                description=f"Package '{pkg}=={version}' has known vulnerability: {cve}.",
                            )
                        )
        return findings


class SuspiciousPackagesRule(SecurityRule):
    """SEC-033: Checks whether dependencies exist and identifies suspicious or hallucinated package names."""
    rule_id = "SEC-033"
    title = "Suspicious or Hallucinated Dependency Package"
    category = "Dependencies"
    severity = Severity.HIGH
    default_status = FindingStatus.POTENTIAL
    description = "Package name appears to be typosquatted, deprecated, or characteristic of LLM hallucination."
    impact = "Installing non-existent or typosquatted packages can result in dependency confusion or supply chain attacks."
    recommendation = "Verify the exact spelling and legitimacy of the package on PyPI or the official package registry."

    DEP_LINE_PATTERN = re.compile(r"^([a-zA-Z0-9_\-\.]+)")

    def scan(self, file_path: str, content: str) -> list[Finding]:
        findings = []
        norm_path = file_path.replace("\\", "/").lower()
        if not (norm_path.endswith("requirements.txt") or "requirements" in norm_path or norm_path.endswith("pyproject.toml")):
            return findings

        for line_no, line in enumerate(content.splitlines(), start=1):
            clean_line = line.strip()
            if clean_line.startswith("#") or not clean_line:
                continue

            match = self.DEP_LINE_PATTERN.match(clean_line)
            if match:
                pkg = match.group(1).lower()
                if pkg in SUSPICIOUS_PACKAGES:
                    reason = SUSPICIOUS_PACKAGES[pkg]
                    findings.append(
                        self.create_finding(
                            file_path=file_path,
                            line_start=line_no,
                            line_end=line_no,
                            code_snippet=clean_line,
                            description=f"Suspicious package '{pkg}' detected: {reason}.",
                        )
                    )
        return findings

